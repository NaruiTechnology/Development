def block_span(text: str, start: int) -> int:
    """Index just past the s-expression that opens at ``start``."""
    depth, i, in_str = 0, start, False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced s-expression")


def remove_block(text: str, head: str, within: tuple[int, int] | None = None) -> str:
    lo, hi = within or (0, len(text))
    m = re.compile(r"\n?[ \t]*\(" + re.escape(head) + r"\b").search(text, lo, hi)
    if not m:
        return text
    open_at = text.index("(", m.start())
    return text[:m.start()] + text[block_span(text, open_at):]


def title_block(rev: str, date: str) -> str:
    return (f'\t(title_block\n\t\t(title "{TITLE}")\n\t\t(date "{date}")\n\t\t(rev "{rev}")\n'
            f'\t\t(company "{COMPANY}")\n'
            '\t\t(comment 1 "2 layers, 1.6 mm FR-4, 1 oz Cu, ENIG, green mask, white silk")\n'
            '\t\t(comment 2 "IPC-6012 Class 2; IPC-A-610 Class 2 assembly; 24 V SELV only")\n'
            '\t\t(comment 3 "Fabrication data: fab/ (generated by tools/make_fab_kicad10.*)")\n'
            "\t)\n")


def prepare(text: str, rev: str, date: str) -> str:
    if not re.search(r'\(generator_version "10\.', text):
        raise SystemExit("expected a KiCad 10 board (generator_version 10.x)")
    text = remove_block(text, "title_block")
    paper = re.search(r'\n\t\(paper "[^"]*"\)\n', text)
    text = text[:paper.end()] + title_block(rev, date) + text[paper.end():]
    setup = re.search(r"\n\t\(setup\b", text)
    s0 = text.index("(", setup.start())
    s1 = block_span(text, s0)
    text = remove_block(text, "stackup", (s0, s1))
    setup = re.search(r"\n\t\(setup\b", text)
    insert = text.index("(setup", setup.start()) + len("(setup")
    insert = text.index("\n", insert) + 1
    return text[:insert] + STACKUP + text[insert:]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("board", type=Path)
    ap.add_argument("--rev", required=True)
    ap.add_argument("--date", required=True)
    args = ap.parse_args(argv)
    text = args.board.read_text()
    new = prepare(text, args.rev, args.date)
    if new != text:
        args.board.write_text(new)
        print(f"{args.board}: title block rev {args.rev} {args.date}, stackup 1.6 mm / 1 oz / ENIG")
    else:
        print(f"{args.board}: already prepared")
    return 0


if __name__ == "__main__":
    sys.exit(main())
