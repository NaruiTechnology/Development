-- stored (num, text) -> JSON value typed by the definition
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_value_json(p_type text, p_num double precision, p_text text)
RETURNS jsonb LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN p_type = 'text'                 THEN CASE WHEN p_text IS NULL THEN NULL ELSE to_jsonb(p_text) END
        WHEN p_num IS NULL                   THEN NULL
        WHEN p_type = 'boolean'              THEN to_jsonb(p_num <> 0)
        WHEN p_type IN ('integer', 'enum')   THEN to_jsonb(round(p_num)::bigint)
        ELSE to_jsonb(p_num)
    END;
$$;

-- request payload value -> {ok, num, text} | {ok:false, message}
-- p_strict_enum: an edit must pick a documented enum value; imports and restores accept what the machine holds
-- (the vendor's comments are not always exhaustive, e.g. IONI_DET_USED is documented 0=E 1=I but is 2 on the supplied machine).
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_coerce(
    d ionbeam_asset.calibration_parameter_definition, v jsonb, p_strict_enum boolean DEFAULT true)
RETURNS jsonb LANGUAGE plpgsql STABLE AS $$
DECLARE
    n double precision;
    s text;
BEGIN
    IF d.value_type = 'text' THEN
        IF v IS NULL OR jsonb_typeof(v) = 'null' THEN
            RETURN jsonb_build_object('ok', true, 'num', NULL, 'text', NULL);
        END IF;
        IF jsonb_typeof(v) <> 'string' THEN
            RETURN jsonb_build_object('ok', false, 'message', 'text value expected');
        END IF;
        RETURN jsonb_build_object('ok', true, 'num', NULL, 'text', v #>> '{}');
    END IF;
    IF v IS NULL OR jsonb_typeof(v) = 'null' OR (jsonb_typeof(v) = 'string' AND btrim(v #>> '{}') = '') THEN
        RETURN jsonb_build_object('ok', false, 'message', 'a value is required');
    END IF;
    IF d.value_type = 'boolean' THEN
        IF jsonb_typeof(v) = 'boolean' THEN
            n := CASE WHEN (v #>> '{}')::boolean THEN 1 ELSE 0 END;
        ELSIF jsonb_typeof(v) = 'number' AND (v #>> '{}')::numeric IN (0, 1) THEN
            n := (v #>> '{}')::numeric;
        ELSIF jsonb_typeof(v) = 'string' AND lower(btrim(v #>> '{}')) IN ('true', '1', 'yes', 'on') THEN
            n := 1;
        ELSIF jsonb_typeof(v) = 'string' AND lower(btrim(v #>> '{}')) IN ('false', '0', 'no', 'off') THEN
            n := 0;
        ELSE
            RETURN jsonb_build_object('ok', false, 'message', 'boolean expected (true/false)');
        END IF;
        RETURN jsonb_build_object('ok', true, 'num', n, 'text', NULL);
    END IF;
    s := btrim(v #>> '{}');
    IF jsonb_typeof(v) NOT IN ('number', 'string') OR s !~ '^[+-]?([0-9]+\.?[0-9]*|\.[0-9]+)([eE][+-]?[0-9]+)?$' THEN
        RETURN jsonb_build_object('ok', false, 'message', 'number expected');
    END IF;
    n := s::double precision;
    IF d.value_type IN ('integer', 'enum') AND n <> round(n) THEN
        RETURN jsonb_build_object('ok', false, 'message', 'integer expected');
    END IF;
    IF d.value_type = 'enum' AND p_strict_enum AND NOT EXISTS (
        SELECT 1 FROM jsonb_array_elements(d.enum_options) o WHERE (o ->> 'value')::numeric = n::numeric
    ) THEN
        RETURN jsonb_build_object('ok', false, 'message',
            'must be one of: ' || (SELECT string_agg((o ->> 'value') || ' (' || (o ->> 'label') || ')', ', ')
                                     FROM jsonb_array_elements(d.enum_options) o));
    END IF;
    RETURN jsonb_build_object('ok', true, 'num', n, 'text', NULL);
END;
$$;

CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_find_profile(
    p_equipment_id integer, p_type text, p_name text DEFAULT NULL)
RETURNS integer LANGUAGE sql STABLE AS $$
    SELECT id FROM ionbeam_asset.calibration_profile
     WHERE equipment_id = p_equipment_id AND equipment_type = p_type
       AND ((p_name IS NOT NULL AND btrim(p_name) <> '' AND profile_name = btrim(p_name))
         OR ((p_name IS NULL OR btrim(p_name) = '') AND is_active))
     ORDER BY is_active DESC, id LIMIT 1;
$$;

-- minimum role (iobeam_admin.user.role: 0 user, 1 super user, 2 developer, 3 admin) that may write a parameter
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_required_role(p_access text)
RETURNS integer LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE p_access WHEN 'adjustable' THEN 1 WHEN 'fixed' THEN 3 ELSE 2 END;
$$;

CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_needs_ack(d ionbeam_asset.calibration_parameter_definition)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN NOT d.semantics_known OR d.param_class = 'undocumented' THEN 'the vendor did not document what this slot does'
        WHEN d.access_level = 'fixed'                                 THEN 'the vendor marks this value as fixed'
        WHEN d.assign_conf = 'low'                                    THEN 'the classification of this parameter is low-confidence'
        ELSE NULL END;
$$;

-- one definition as JSON (the shape of CalibrationParameterDefinition in calibrationRepository.ts + extensions)
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_definition_json(
    d ionbeam_asset.calibration_parameter_definition, p_category text,
    p_dyn_min double precision DEFAULT NULL, p_dyn_max double precision DEFAULT NULL)
RETURNS jsonb LANGUAGE sql STABLE AS $$
    SELECT jsonb_build_object(
        'id', d.id, 'equipment_type', d.equipment_type, 'parameter_key', d.parameter_key,
        'category', p_category, 'display_name', d.display_name, 'description', d.description,
        'value_type', d.value_type, 'unit', d.unit,
        'minimum_value', COALESCE(d.minimum_value, p_dyn_min), 'maximum_value', COALESCE(d.maximum_value, p_dyn_max),
        'default_value', d.default_value,
        'enum_values', COALESCE((SELECT jsonb_agg(o ->> 'label') FROM jsonb_array_elements(d.enum_options) o), '[]'::jsonb),
        'source_vendor', d.source_vendor, 'source_document', d.source_document, 'source_url', d.source_url,
        'source_reference', d.source_reference, 'is_read_only', d.is_read_only, 'sort_order', d.sort_order
    ) || jsonb_build_object(
        'group_code', d.group_code, 'vendor_name', d.vendor_name, 'param_class', d.param_class,
        'access_level', d.access_level, 'ui_widget', d.ui_widget,
        'enum_options', COALESCE(d.enum_options, '[]'::jsonb), 'unit_source', d.unit_source,
        'table_code', d.table_code, 'row_key', d.row_key, 'col_key', d.col_key,
        'semantics_known', d.semantics_known, 'assign_basis', d.assign_basis, 'assign_conf', d.assign_conf,
        'review_state', d.review_state, 'applicability', to_jsonb(d.applicability),
        'shared_hardware', d.shared_hardware, 'adjustment_no', d.adjustment_no,
        'limit_min_key', d.limit_min_key, 'limit_max_key', d.limit_max_key
    );
$$;

-- profile row -> JSON
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_profile_json(p ionbeam_asset.calibration_profile)
RETURNS jsonb LANGUAGE sql STABLE AS $$
    SELECT jsonb_build_object('id', p.id, 'equipment_id', p.equipment_id, 'equipment_type', p.equipment_type,
                              'profile_name', p.profile_name, 'revision', p.revision, 'notes', p.notes,
                              'is_active', p.is_active, 'updated_at', p.updated_at, 'updated_by', p.updated_by);
$$;

-- every stored value of a profile as {parameter_key: json}
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_snapshot(p_profile_id integer)
RETURNS jsonb LANGUAGE sql STABLE AS $$
    SELECT COALESCE(jsonb_object_agg(d.parameter_key, ionbeam_asset.fn_calibration_value_json(d.value_type, v.value_num, v.value_text)), '{}'::jsonb)
      FROM ionbeam_asset.calibration_value v
      JOIN ionbeam_asset.calibration_parameter_definition d ON d.id = v.definition_id
     WHERE v.profile_id = p_profile_id AND (v.value_num IS NOT NULL OR v.value_text IS NOT NULL);
$$;

-- =====================================================================================================
-- write path: validate -> (optionally) apply. Used by upsert, restore and import.
-- =====================================================================================================
CREATE OR REPLACE FUNCTION ionbeam_asset.fn_calibration_apply(
    p_profile_id        integer,
    p_items             jsonb,            -- [{parameter_key, value, notes?, verified?}]
    p_kind              text,             -- edit | import | restore
    p_reason            text,
    p_actor             integer,
    p_actor_role        integer,
    p_ack               boolean,
    p_expected_revision integer,
    p_source_ref        text,
    p_enforce           boolean,          -- role + risk-acknowledgement checks
    p_check_limits      boolean,
    p_dry_run           boolean)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    prof        ionbeam_asset.calibration_profile%ROWTYPE;
    it          jsonb;
    d           ionbeam_asset.calibration_parameter_definition%ROWTYPE;
    c           jsonb;
    cur         ionbeam_asset.calibration_value%ROWTYPE;
    key         text;
    errors      jsonb := '[]'::jsonb;
    warnings    jsonb := '[]'::jsonb;
    changes     jsonb := '[]'::jsonb;
    newvals     jsonb := '{}'::jsonb;           -- key -> numeric value proposed in this request (for limit checks)
    proposed    jsonb := '[]'::jsonb;           -- [{def_id, key, num, text, notes, verified, old, new, changed}]
    ack_needed  jsonb := '[]'::jsonb;
    ack_reason  text;
    lo double precision; hi double precision;
    lim double precision;
    prop        jsonb;
    unchanged   integer := 0;
    annotated   integer := 0;
    n_changed   integer := 0;
    new_rev     integer;
    snap        jsonb;
    seen        text[] := ARRAY[]::text[];
BEGIN
    SELECT * INTO prof FROM ionbeam_asset.calibration_profile WHERE id = p_profile_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('ok', false, 'error', 'profile not found');
    END IF;
    IF p_expected_revision IS NOT NULL AND p_expected_revision <> prof.revision THEN
        RETURN jsonb_build_object('ok', false, 'error', 'revision_conflict',
            'message', format('the profile is at revision %s but you edited revision %s - reload and retry', prof.revision, p_expected_revision),
            'current_revision', prof.revision);
    END IF;

    -- pass 1: resolve, coerce, role / acknowledgement --------------------------------------------------
    FOR it IN SELECT value FROM jsonb_array_elements(COALESCE(p_items, '[]'::jsonb))
    LOOP
        key := btrim(COALESCE(it ->> 'parameter_key', ''));
        SELECT * INTO d FROM ionbeam_asset.calibration_parameter_definition
         WHERE equipment_type = prof.equipment_type AND parameter_key = key AND is_active;
        IF NOT FOUND THEN
            errors := errors || jsonb_build_object('parameter_key', key, 'code', 'unknown_parameter',
                        'message', format('%s has no parameter "%s"', prof.equipment_type, key));
            CONTINUE;
        END IF;
        IF key = ANY (seen) THEN
            errors := errors || jsonb_build_object('parameter_key', key, 'code', 'duplicate', 'message', 'parameter listed twice');
            CONTINUE;
        END IF;
        seen := array_append(seen, key);

        IF COALESCE((it ->> 'clear')::boolean, false) THEN
            c := jsonb_build_object('ok', true, 'num', NULL, 'text', NULL);       -- remove the stored value
        ELSE
            c := ionbeam_asset.fn_calibration_coerce(d, it -> 'value', p_kind = 'edit');
            IF NOT (c ->> 'ok')::boolean THEN
                errors := errors || jsonb_build_object('parameter_key', key, 'code', 'invalid_value', 'message', c ->> 'message');
                CONTINUE;
            END IF;
        END IF;

        SELECT * INTO cur FROM ionbeam_asset.calibration_value WHERE profile_id = p_profile_id AND definition_id = d.id;
        prop := jsonb_build_object(
            'def_id', d.id, 'key', key, 'num', c -> 'num', 'text', c -> 'text',
            'notes', it -> 'notes', 'verified', COALESCE((it ->> 'verified')::boolean, false),
            'old', CASE WHEN FOUND THEN ionbeam_asset.fn_calibration_value_json(d.value_type, cur.value_num, cur.value_text) END,
            'new', ionbeam_asset.fn_calibration_value_json(d.value_type, (c ->> 'num')::double precision, c ->> 'text'),
            'changed', (NOT FOUND) OR cur.value_num IS DISTINCT FROM (c ->> 'num')::double precision
                                    OR cur.value_text IS DISTINCT FROM (c ->> 'text'),
            'has_row', FOUND,
            'clear', COALESCE((it ->> 'clear')::boolean, false));
        IF (prop ->> 'changed')::boolean AND jsonb_typeof(prop -> 'new') = 'null' AND jsonb_typeof(prop -> 'old') = 'null' THEN
            prop := jsonb_set(prop, '{changed}', 'false');      -- NULL -> NULL is not a change
        END IF;

        IF p_enforce AND (prop ->> 'changed')::boolean THEN
            IF p_actor_role < ionbeam_asset.fn_calibration_required_role(d.access_level) THEN
                errors := errors || jsonb_build_object('parameter_key', key, 'code', 'forbidden_role',
                    'message', format('%s parameters need role %s or higher', d.access_level, ionbeam_asset.fn_calibration_required_role(d.access_level)));
                CONTINUE;
            END IF;
            ack_reason := ionbeam_asset.fn_calibration_needs_ack(d);
            IF ack_reason IS NOT NULL AND NOT COALESCE(p_ack, false) THEN
                ack_needed := ack_needed || jsonb_build_object('parameter_key', key, 'code', 'risk_ack_required', 'message', ack_reason);
            END IF;
        END IF;
        IF (c ->> 'num') IS NOT NULL THEN
            newvals := newvals || jsonb_build_object(key, (c -> 'num'));
        END IF;
        proposed := proposed || prop;
    END LOOP;

    -- pass 2: limits (static bounds, then bounds held in other parameters) -------------------------------
    IF p_check_limits THEN
        FOR prop IN SELECT value FROM jsonb_array_elements(proposed)
        LOOP
            CONTINUE WHEN NOT (prop ->> 'changed')::boolean OR (prop -> 'num') IS NULL OR jsonb_typeof(prop -> 'num') = 'null';
            SELECT * INTO d FROM ionbeam_asset.calibration_parameter_definition WHERE id = (prop ->> 'def_id')::integer;
            lo := d.minimum_value;  hi := d.maximum_value;
            IF lo IS NULL AND d.limit_min_key IS NOT NULL THEN
                lo := COALESCE((newvals ->> d.limit_min_key)::double precision,
                               (SELECT v.value_num FROM ionbeam_asset.calibration_value v
                                  JOIN ionbeam_asset.calibration_parameter_definition x ON x.id = v.definition_id
                                 WHERE v.profile_id = p_profile_id AND x.equipment_type = prof.equipment_type AND x.parameter_key = d.limit_min_key));
            END IF;
            IF hi IS NULL AND d.limit_max_key IS NOT NULL THEN
                hi := COALESCE((newvals ->> d.limit_max_key)::double precision,
                               (SELECT v.value_num FROM ionbeam_asset.calibration_value v
                                  JOIN ionbeam_asset.calibration_parameter_definition x ON x.id = v.definition_id
                                 WHERE v.profile_id = p_profile_id AND x.equipment_type = prof.equipment_type AND x.parameter_key = d.limit_max_key));
            END IF;
            lim := (prop ->> 'num')::double precision;
            -- an unset / inverted pair (0/0, min>max) means "no limit" in the vendor files
            IF lo IS NOT NULL AND hi IS NOT NULL AND lo <= hi AND NOT (lo = 0 AND hi = 0) AND (lim < lo OR lim > hi) THEN
                errors := errors || jsonb_build_object('parameter_key', d.parameter_key, 'code', 'out_of_range',
                            'message', format('outside the vendor limits [%s .. %s]', lo, hi));
            END IF;
        END LOOP;
    END IF;

    IF jsonb_array_length(errors) > 0 OR jsonb_array_length(ack_needed) > 0 THEN
        RETURN jsonb_build_object('ok', false,
            'error', CASE WHEN jsonb_array_length(errors) > 0 THEN 'validation_failed' ELSE 'risk_ack_required' END,
            'errors', errors || ack_needed);
    END IF;

    -- summarise ----------------------------------------------------------------------------------------
    FOR prop IN SELECT value FROM jsonb_array_elements(proposed)
    LOOP
        IF (prop ->> 'changed')::boolean THEN
            n_changed := n_changed + 1;
            changes := changes || jsonb_build_object('parameter_key', prop ->> 'key', 'old', prop -> 'old', 'new', prop -> 'new');
        ELSE
            unchanged := unchanged + 1;
        END IF;
    END LOOP;

    IF p_dry_run THEN
        RETURN jsonb_build_object('ok', true, 'dry_run', true, 'revision', prof.revision, 'changed', n_changed,
                                  'unchanged', unchanged, 'changes', changes);
    END IF;

    -- write --------------------------------------------------------------------------------------------
    FOR prop IN SELECT value FROM jsonb_array_elements(proposed)
    LOOP
        IF (prop ->> 'changed')::boolean AND (prop ->> 'clear')::boolean THEN
            DELETE FROM ionbeam_asset.calibration_value
             WHERE profile_id = p_profile_id AND definition_id = (prop ->> 'def_id')::integer;
        ELSIF (prop ->> 'changed')::boolean THEN
            INSERT INTO ionbeam_asset.calibration_value AS v (profile_id, definition_id, value_num, value_text, notes, verified_at, update_date)
            VALUES (p_profile_id, (prop ->> 'def_id')::integer,
                    (prop ->> 'num')::double precision, prop ->> 'text',
                    COALESCE(prop ->> 'notes', ''), CASE WHEN (prop ->> 'verified')::boolean THEN CURRENT_TIMESTAMP END, CURRENT_TIMESTAMP)
            ON CONFLICT (profile_id, definition_id) DO UPDATE
               SET value_num = EXCLUDED.value_num, value_text = EXCLUDED.value_text,
                   notes = COALESCE(prop ->> 'notes', v.notes),
                   verified_at = CASE WHEN (prop ->> 'verified')::boolean THEN CURRENT_TIMESTAMP ELSE v.verified_at END,
                   update_date = CURRENT_TIMESTAMP;
        ELSIF (prop ->> 'has_row')::boolean AND ((prop ->> 'notes') IS NOT NULL OR (prop ->> 'verified')::boolean) THEN
            UPDATE ionbeam_asset.calibration_value
               SET notes = COALESCE(prop ->> 'notes', notes),
                   verified_at = CASE WHEN (prop ->> 'verified')::boolean THEN CURRENT_TIMESTAMP ELSE verified_at END,
                   update_date = CURRENT_TIMESTAMP
             WHERE profile_id = p_profile_id AND definition_id = (prop ->> 'def_id')::integer;
            annotated := annotated + 1;
        END IF;
    END LOOP;

    new_rev := prof.revision;
    IF n_changed > 0 THEN
        new_rev := prof.revision + 1;
        snap := ionbeam_asset.fn_calibration_snapshot(p_profile_id);
        INSERT INTO ionbeam_asset.calibration_revision (profile_id, revision, kind, reason, source_ref, changes, changed_count, full_snapshot, created_by)
        VALUES (p_profile_id, new_rev, p_kind, COALESCE(p_reason, ''), COALESCE(p_source_ref, ''), changes, n_changed, snap, p_actor);
        UPDATE ionbeam_asset.calibration_profile
           SET revision = new_rev, updated_at = CURRENT_TIMESTAMP, updated_by = p_actor
         WHERE id = p_profile_id;
    END IF;

    RETURN jsonb_build_object('ok', true, 'revision', new_rev, 'changed', n_changed, 'unchanged', unchanged,
                              'annotated', annotated, 'changes', changes, 'warnings', warnings);
END;
$$;

