-- =====================================================================================================
-- 003_calibration_schema.sql  -  FIB | SEM equipment calibration-parameter management
--
-- Loaded after 001_schema.sql (and 002 when seeding) by applyAdminDatabaseSetup(); fully idempotent, like
-- 001. Objects live in the existing `ionbeam_asset` schema, next to ionbeam_asset.equipment, so a profile
-- is a real foreign-key child of a registered machine (DB235, FIB200, ...).
--
--   calibration_group / calibration_table   navigation tree and matrix / list layouts
--   calibration_parameter_definition        the catalog: one row per parameter (or one cell of a table)
--   calibration_profile                     (equipment, FIB|SEM) -> named profile with a revision counter
--   calibration_value                       current value of each parameter in a profile
--   calibration_revision                    append-only history: what changed + full snapshot per revision
--   calibration_definition_change           audit of catalog edits (e.g. naming a vendor-undocumented slot)
--
-- The catalog is loaded by 004_calibration_seed.sql (generated) via fn_seed_calibration_catalog().
-- Vendor credentials found in the machine-data files (IONI_PSWD1-4, usr\*\LOGIN\KEY) are NEVER catalogued.
--
-- Public functions (all take / return jsonb, called by ionbeam-web/backend/src/calibrationRepository.ts):
--   fn_list_calibration_groups            fn_get_equipment_calibration           fn_get_calibration_table
--   fn_upsert_equipment_calibration       fn_list_equipment_calibration_history
--   fn_restore_equipment_calibration_revision   fn_import_equipment_calibration
--   fn_update_calibration_definition      fn_seed_calibration_catalog
-- =====================================================================================================
CREATE SCHEMA IF NOT EXISTS iobeam_admin;
CREATE SCHEMA IF NOT EXISTS ionbeam_asset;
SET search_path TO ionbeam_asset, iobeam_admin, public;

-- ------------------------------------------------------------------------------------- navigation
CREATE TABLE IF NOT EXISTS ionbeam_asset.calibration_group (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_type varchar(3)   NOT NULL CHECK (equipment_type IN ('FIB', 'SEM')),
    group_code     varchar(60)  NOT NULL,
    parent_code    varchar(60),
    label          varchar(200) NOT NULL,
    sort_order     integer      NOT NULL DEFAULT 0,
    UNIQUE (equipment_type, group_code)
);

CREATE TABLE IF NOT EXISTS ionbeam_asset.calibration_table (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_type varchar(3)   NOT NULL CHECK (equipment_type IN ('FIB', 'SEM')),
    table_code     varchar(60)  NOT NULL,
    group_code     varchar(60)  NOT NULL,
    label          varchar(200) NOT NULL,
    kind           varchar(10)  NOT NULL CHECK (kind IN ('matrix', 'list')),
    row_header     varchar(100),
    col_header     varchar(100),
    note           text,
    layout         jsonb        NOT NULL DEFAULT '{"rows":[],"cols":[]}'::jsonb,   -- {rows:[{key,label,role}], cols:[{key,label,unit}]}
    UNIQUE (equipment_type, table_code),
    FOREIGN KEY (equipment_type, group_code) REFERENCES ionbeam_asset.calibration_group (equipment_type, group_code)
);

-- ------------------------------------------------------------------------------------- catalog
CREATE TABLE IF NOT EXISTS ionbeam_asset.calibration_parameter_definition (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_type  varchar(3)    NOT NULL CHECK (equipment_type IN ('FIB', 'SEM')),
    parameter_key   varchar(200)  NOT NULL,
    group_code      varchar(60)   NOT NULL,
    vendor_name     varchar(200),                               -- vendor symbol as written; NULL = vendor gave none
    display_name    varchar(300)  NOT NULL,
    description     text          NOT NULL DEFAULT '',
    value_type      varchar(10)   NOT NULL CHECK (value_type IN ('number', 'integer', 'boolean', 'text', 'enum')),
    unit            varchar(30)   NOT NULL DEFAULT '',
    unit_source     varchar(10)   CHECK (unit_source IN ('vendor', 'name', 'inferred')),
    minimum_value   double precision,                           -- static bounds
    maximum_value   double precision,
    limit_min_key   varchar(200),                               -- bounds held in other parameters of the same profile
    limit_max_key   varchar(200),
    default_value   jsonb,                                      -- vendor factory value where the vendor supplied one
    enum_options    jsonb,                                      -- [{"value":3,"label":"FIB600"}, ...]
    param_class     varchar(15)   NOT NULL CHECK (param_class IN
                        ('identity', 'config', 'calibration', 'tuning', 'limit', 'preset', 'counter', 'unused', 'undocumented')),
    access_level    varchar(10)   NOT NULL CHECK (access_level IN ('fixed', 'auto', 'service', 'adjustable')),
    is_read_only    boolean       NOT NULL DEFAULT false,
    shared_hardware boolean       NOT NULL DEFAULT false,       -- one physical device serves both FIB and SEM (stage, pumps)
    applicability   text[]        NOT NULL DEFAULT '{}',
    ui_widget       varchar(10)   NOT NULL DEFAULT 'number' CHECK (ui_widget IN ('number', 'toggle', 'select', 'readonly', 'raw', 'text')),
    adjustment_no   varchar(10),
    table_code      varchar(60),                                -- set => this definition is one cell of a table
    row_key         varchar(60),
    col_key         varchar(60),
    source_vendor   varchar(100)  NOT NULL DEFAULT '',
    source_document varchar(200)  NOT NULL DEFAULT '',
    source_url      varchar(500)  NOT NULL DEFAULT '',
    source_reference varchar(500) NOT NULL DEFAULT '',
    source_kind     varchar(5)    CHECK (source_kind IN ('int', 'float', 'reg')),
    source_slot     integer,
    source_path     varchar(500),                               -- registry leaf path (import matching key)
    source_line     integer,
    vendor_flags    varchar(60),
    semantics_known boolean       NOT NULL DEFAULT true,        -- false = the vendor never documented the meaning
    assign_basis    varchar(15)   CHECK (assign_basis IN ('vendor_file', 'registry_path', 'name_rule', 'default', 'manual')),
    assign_conf     varchar(6)    CHECK (assign_conf IN ('high', 'medium', 'low')),
    review_state    varchar(10)   NOT NULL DEFAULT 'imported' CHECK (review_state IN ('imported', 'reviewed', 'confirmed')),
    is_active       boolean       NOT NULL DEFAULT true,
    sort_order      integer       NOT NULL DEFAULT 0,
    update_date     timestamp(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (equipment_type, parameter_key),
    FOREIGN KEY (equipment_type, group_code) REFERENCES ionbeam_asset.calibration_group (equipment_type, group_code),
    FOREIGN KEY (equipment_type, table_code) REFERENCES ionbeam_asset.calibration_table (equipment_type, table_code),
    CONSTRAINT calibration_cell_all_or_none
        CHECK ((table_code IS NULL) = (row_key IS NULL) AND (table_code IS NULL) = (col_key IS NULL)),
    CONSTRAINT calibration_enum_needs_options CHECK (value_type <> 'enum' OR enum_options IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_calibration_def_cell
    ON ionbeam_asset.calibration_parameter_definition (equipment_type, table_code, row_key, col_key) WHERE table_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_calibration_def_group
    ON ionbeam_asset.calibration_parameter_definition (equipment_type, group_code, sort_order);
CREATE INDEX IF NOT EXISTS idx_calibration_def_slot
    ON ionbeam_asset.calibration_parameter_definition (equipment_type, source_kind, source_slot) WHERE source_slot IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_calibration_def_path
    ON ionbeam_asset.calibration_parameter_definition (equipment_type, source_path) WHERE source_path IS NOT NULL;

-- ------------------------------------------------------------------------------------- profiles & values
CREATE TABLE IF NOT EXISTS ionbeam_asset.calibration_profile (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id   integer      NOT NULL REFERENCES ionbeam_asset.equipment (id) ON DELETE CASCADE,
    equipment_type varchar(3)   NOT NULL CHECK (equipment_type IN ('FIB', 'SEM')),
    profile_name   varchar(100) NOT NULL DEFAULT 'default',
    revision       integer      NOT NULL DEFAULT 0,
    notes          text         NOT NULL DEFAULT '',
    is_active      boolean      NOT NULL DEFAULT true,
    updated_at     timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     integer      REFERENCES iobeam_admin."user" (id) ON DELETE SET NULL,
    UNIQUE (equipment_id, equipment_type, profile_name)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_calibration_profile_active
    ON ionbeam_asset.calibration_profile (equipment_id, equipment_type) WHERE is_active;

CREATE TABLE IF NOT EXISTS ionbeam_asset.calibration_value (
    profile_id    integer NOT NULL REFERENCES ionbeam_asset.calibration_profile (id) ON DELETE CASCADE,
    definition_id integer NOT NULL REFERENCES ionbeam_asset.calibration_parameter_definition (id) ON DELETE RESTRICT,
    value_num     double precision,
    value_text    text,
    notes         text         NOT NULL DEFAULT '',
    verified_at   timestamp(6),
    update_date   timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (profile_id, definition_id),
    CHECK (value_num IS NULL OR value_text IS NULL)
);
CREATE INDEX IF NOT EXISTS idx_calibration_value_def ON ionbeam_asset.calibration_value (definition_id);

CREATE TABLE IF NOT EXISTS ionbeam_asset.calibration_revision (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id    integer      NOT NULL REFERENCES ionbeam_asset.calibration_profile (id) ON DELETE CASCADE,
    revision      integer      NOT NULL,
    kind          varchar(10)  NOT NULL CHECK (kind IN ('edit', 'import', 'restore')),
    reason        text         NOT NULL DEFAULT '',
    source_ref    varchar(300) NOT NULL DEFAULT '',          -- file name for imports, 'revision N' for restores
    changes       jsonb        NOT NULL DEFAULT '[]'::jsonb, -- [{parameter_key, old, new}]
    changed_count integer      NOT NULL DEFAULT 0,
    full_snapshot jsonb        NOT NULL DEFAULT '{}'::jsonb, -- every value of the profile after this revision
    created_at    timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by    integer      REFERENCES iobeam_admin."user" (id) ON DELETE SET NULL,
    UNIQUE (profile_id, revision)
);

